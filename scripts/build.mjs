import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

async function build() {
  console.log("[build] Building md-questioner client assets and CLI...");

  // 1. Bundle React Client
  const entryPath = path.resolve(rootDir, "src/render/entry.tsx");
  console.log(`[build] Bundling React client from ${entryPath}`);
  const clientBuild = await esbuild.build({
    entryPoints: [entryPath],
    bundle: true,
    format: "iife",
    minify: true,
    target: ["es2020"],
    platform: "browser",
    write: false,
    jsx: "automatic",
    define: {
      "process.env.NODE_ENV": '"production"',
    },
  });
  const clientJs = clientBuild.outputFiles?.[0]?.text || "";

  // 2. Bundle Styles (tokens.css + global.css)
  const tokensPath = path.resolve(rootDir, "src/styles/tokens.css");
  const globalPath = path.resolve(rootDir, "src/styles/global.css");
  let tokensCss = "";
  let globalCss = "";
  try {
    tokensCss = await fs.readFile(tokensPath, "utf-8");
  } catch {}
  try {
    globalCss = await fs.readFile(globalPath, "utf-8");
  } catch {}

  const rawCss = `${tokensCss}\n${globalCss}`;
  const cssTransform = await esbuild.transform(rawCss, {
    loader: "css",
    minify: true,
  });
  const clientCss = cssTransform.code;

  // 3. Emit src/bundle/client-bundle.generated.ts
  const generatedPath = path.resolve(rootDir, "src/bundle/client-bundle.generated.ts");
  const generatedContent = `// Auto-generated by scripts/build.mjs - DO NOT EDIT MANUALLY
export const clientJs: string = ${JSON.stringify(clientJs)};
export const clientCss: string = ${JSON.stringify(clientCss)};
export default { clientJs, clientCss };
`;
  await fs.writeFile(generatedPath, generatedContent, "utf-8");
  console.log(
    `[build] Generated client bundle: ${(Buffer.byteLength(clientJs) / 1024).toFixed(1)} KB JS, ${(Buffer.byteLength(clientCss) / 1024).toFixed(1)} KB CSS`
  );

  // 4. Bundle CLI entry point src/cli.ts into dist/scripts/md-questioner.cjs
  const distScriptsDir = path.resolve(rootDir, "dist/scripts");
  await fs.mkdir(distScriptsDir, { recursive: true });
  const cliOutPath = path.resolve(distScriptsDir, "md-questioner.mjs");

  console.log(`[build] Bundling CLI to ${cliOutPath}...`);
  await esbuild.build({
    entryPoints: [path.resolve(rootDir, "src/cli.ts")],
    bundle: true,
    outfile: cliOutPath,
    platform: "node",
    target: ["node20"],
    format: "esm",
    sourcemap: false,
    minify: false,
    banner: {
      js: "#!/usr/bin/env node\nimport { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);\n",
    },
    external: ["esbuild", "playwright"],
  });

  // Make CLI script executable
  try {
    await fs.chmod(cliOutPath, 0o755);
  } catch {}

  // Also write build/cli.js
  const buildDir = path.resolve(rootDir, "build");
  await fs.mkdir(buildDir, { recursive: true });
  await fs.copyFile(cliOutPath, path.resolve(buildDir, "cli.js"));

  // 5. Bundle verify/headless.ts
  const distVerifyDir = path.resolve(rootDir, "dist/verify");
  await fs.mkdir(distVerifyDir, { recursive: true });
  await esbuild.build({
    entryPoints: [path.resolve(rootDir, "src/verify/headless.ts")],
    bundle: true,
    outfile: path.resolve(distVerifyDir, "headless.js"),
    platform: "node",
    target: ["node20"],
    format: "esm",
    external: ["playwright"],
  });

  console.log("[build] Build completed successfully.");
}

build().catch((err) => {
  console.error("[build] Error during build:", err);
  process.exit(1);
});
